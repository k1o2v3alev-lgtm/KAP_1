def ntex(x):
    x = F(x)
    d = x.denominator
    while d % 2 == 0: d //= 2
    while d % 5 == 0: d //= 5
    if d == 1: return dtex(x)
    return ('-' if x < 0 else '') + r'\frac{%d}{%d}' % (abs(x.numerator), x.denominator)
def M(s): return '$%s$' % s
def mx(x, unit=''): return M(ntex(x)) + (' ' + unit if unit else '')

class Item(dict): pass

def mk(work, var, no, goal, topic, skill, stem, correct, wrongs, fmt=None, src='R0', fig=None, note=''):
    """correct/wrongs — значения (Fraction/str/sympy); fmt: значение -> строка опции (rich)."""
    fmt = fmt or (lambda v: M(ntex(v)))
    def key(v): return v if isinstance(v, str) else (F(v) if not isinstance(v, sp.Basic) else sp.srepr(sp.nsimplify(v)))
    seen = {key(correct)}; ws = []
    for w in wrongs:
        k = key(w)
        if k in seen: continue
        seen.add(k); ws.append(w)
        if len(ws) == 3: break
    assert len(ws) == 3, (work, var, no, 'мало дистракторов', wrongs)
    opts = [(fmt(correct), True)] + [(fmt(w), False) for w in ws]
    assert len({o for o, _ in opts}) == 4, (work, var, no, [o for o, _ in opts])
    return Item(work=work, variant=var, no=no, goal=goal, topic=topic, skill=skill, stem=stem, options=opts, src=src, fig=fig, note=note, value=correct)

