def shade(cell, color='E8EEF3'):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), color); tcPr.append(sh)
def para(text='', bold=False, size=None, align=None, space_after=4, italic=False, color=None):
    p = doc.add_paragraph(); r = p.add_run(text); r.bold = bold; r.italic = italic
    if size: r.font.size = Pt(size)
    if color: r.font.color.rgb = RGBColor.from_string(color)
    if align == 'c': p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(space_after); p.paragraph_format.space_before = Pt(0); return p
def cell_text(cell, text, bold=False, size=10, align=None):
    cell.text = ''; p = cell.paragraphs[0]
    lines = text.split('\n')
    for i, ln in enumerate(lines):
        if i: p = cell.add_paragraph()
        r = p.add_run(ln); r.bold = bold; r.font.size = Pt(size); p.paragraph_format.space_after = Pt(1)
        if align == 'c': p.alignment = WD_ALIGN_PARAGRAPH.CENTER
def table(rows, widths, header_rows=1, size=10, center_cols=()):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.autofit = False
    tblPr = t._tbl.tblPr; lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); tblPr.append(lay)
    for j, wd in enumerate(widths): t.columns[j].width = Cm(wd)
    for i, row in enumerate(rows):
        for j, txt in enumerate(row):
            c = t.cell(i, j); c.width = Cm(widths[j]); cell_text(c, txt, bold=(i < header_rows), size=size, align='c' if (i < header_rows or j in center_cols) else None)
            if i < header_rows: shade(c)
    return t

