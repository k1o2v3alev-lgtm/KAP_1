SUP = {'2': '²', '3': '³'}
def plain(t):
    t = '$'.join(p.replace('-', '−') if i % 2 else p for i, p in enumerate(t.split('$')))
    t = t.replace('$', '')
    t = t.replace('{,}', ',').replace('\\,', ' ').replace('\\ ', ' ').replace('\\cdot', '·').replace('\\neq', '≠').replace('\\left', '').replace('\\right', '').replace('\\{', '{').replace('\\}', '}')
    for _ in range(3):
        def fr(mm):
            n_, d_ = mm.group(1), mm.group(2)
            wrap = lambda x: '(%s)' % x if re.search(r'[+\-−a-z·:]', x) and len(x) > 1 else x
            return '%s/%s' % (wrap(n_), wrap(d_))
        t = re.sub(r'\\frac\{([^{}]*)\}\{([^{}]*)\}', fr, t)
    t = re.sub(r'\^\{(\d)\}', lambda m: SUP.get(m.group(1), '^' + m.group(1)), t)
    t = re.sub(r'(−?)(\d+) (\d+/\d+)', r'(\1\2 \3)', t)
    t = t.replace('\u00a0', ' ').replace('  ', ' ').replace('{', '').replace('}', '')
    return t.strip()
