#!/usr/bin/env python3
"""
Независимая перепроверка ключей трёх вариантов «Математическая грамотность» (11 кл.)
Варианты: 18461, 16498, 16979 (Решу ЕНТ).

Для каждого задания:
  * ответ считается кодом «с нуля» (не берётся из ключа);
  * находится номер варианта ответа, совпадающий с вычисленным;
  * проверяется, что такой вариант ровно один;
  * сравнивается с ключом из PDF.

Значения, снятые с рисунков (графики, диаграммы, таблица-закономерность), вынесены
в явные константы с пометкой «ПО РИСУНКУ» — их нужно сверять глазами с картинкой.

Запуск:  python3 -I verify_keys.py
"""
from fractions import Fraction as F
from itertools import permutations
from math import comb
from collections import Counter

RESULTS = []  # (вариант, №, ключ в PDF, вычислено, статус, комментарий)


def check(variant, n, key_pdf, options, computed, note=""):
    """options: список значений 1..4 (значения сравниваются через ==)."""
    hits = [i + 1 for i, o in enumerate(options) if o == computed]
    if len(hits) == 1:
        got = hits[0]
        status = "OK" if got == key_pdf else "ОШИБКА КЛЮЧА"
    elif len(hits) == 0:
        got, status = None, "НЕТ ВЕРНОГО ВАРИАНТА"
    else:
        got, status = hits, "НЕСКОЛЬКО ВЕРНЫХ"
    RESULTS.append((variant, n, key_pdf, got, status, note))


# =============================== ВАРИАНТ 18461 ===============================
V = 18461
# 1. A = 7^5·7^6/7^10, B = 3^4·3^7/3^9
A = F(7) ** 5 * F(7) ** 6 / F(7) ** 10
B = F(3) ** 4 * F(3) ** 7 / F(3) ** 9
truth = [B - A == 3, A == B - 4, A == B - 2, A == B]          # истинность утверждений 1..4
check(V, 1, 3, truth, True, f"A={A}, B={B}, B-A={B-A}")

# 2. Время забега — ПО РИСУНКУ (подписи столбцов)
times = [F("16.2"), F("22.4"), F("16.2"), F("15.5"), F("18.2"), F("14.1")]
check(V, 2, 1, [F("8.3"), F("16.2"), F("15.5"), F("18.2")], max(times) - min(times),
      "размах = 22,4 − 14,1")

# 3. Медиана выборки a1..a5 с абсолютными частотами 12,10,8,3,5 (значения упорядочены a1<…<a5)
freq = [12, 10, 8, 3, 5]
series = [i for i, f in enumerate(freq, start=1) for _ in range(f)]   # индексы элементов вариационного ряда
N = len(series)
lo, hi = series[(N - 1) // 2], series[N // 2]
assert lo == hi
check(V, 3, 1, [3, 1, 2, 4], lo,
      f"N={N}, 19-й и 20-й члены ряда = a{lo}; в PDF ключ 1 → a3. Медиана ЧАСТОТ (3,5,8,10,12) = 8 = частота a3 — вероятная причина ошибки")

# 4. «информация»: вероятность буквы «и»
w = "информация"
p = F(w.count("и"), len(w))
check(V, 4, 1, [F(1, 5), F(7, 10), F(4, 5), F(2, 5)], p, f"{w.count('и')}/{len(w)}")

# 5. Квадрат разбит двумя отрезками. Периметры: левый верхний = 6, правый нижний = 18.
#    a+b = P1/2 ; (s-a)+(s-b) = P2/2  →  s = (P1+P2)/4
P1, P2 = 6, 18
s = F(P1 + P2, 4)
check(V, 5, 1, [6, 12, 9, 8], s, "s=(6+18)/4; ЕДИНИЦЫ: на рисунке «м», в ответах «см»")

# 6. График осадков — ПО РИСУНКУ (мм по дням 3..15)
rain = {3: .3, 4: 4, 5: 0, 6: 2, 8: 0, 9: 0, 10: 2.5, 11: 5, 12: 0, 13: 1.6, 14: .5, 15: 6}
first5 = min(d for d, v in rain.items() if v == 5)
check(V, 6, 1, [11, 15, 9, 12], first5, "5 мм ровно один раз (11-го) → «впервые» избыточно")

# 7. Шахматный турнир, 9 участников, каждый с каждым
check(V, 7, 4, [48, 81, 18, 36], comb(9, 2))

# 8. Таблица-закономерность 3×3 — ПО РИСУНКУ:  x 6 7,5 / 9 [ ] 3 / 37,5 6 22,5
#    Закономерность: сумма двух угловых клеток по краю = 10 × клетка между ними
T, Bm, L, R = F(6), F(6), F(9), F(3)
TR, BL, BR = F("7.5"), F("37.5"), F("22.5")
k = F(10)
assert (BL + BR) == k * Bm and (TR + BR) == k * R           # проверка закономерности на известных рёбрах
x_from_top = k * T - TR
x_from_left = k * L - BL
assert x_from_top == x_from_left
check(V, 8, 1, [F("52.5"), F("40.5"), F(20), F("60.5")], x_from_top,
      "x=10·6−7,5=10·9−37,5; условие согласованности T+B=L+R выполнено (6+6=9+3)")

# 9. Букет: гвоздик = 3N/4 − 9; остальные R=N−гв; розы = R/2+3; хризантем 5
sol = []
for Nn in range(1, 300):
    carn = F(3, 4) * Nn - 9
    if carn <= 0 or carn.denominator != 1:
        continue
    Rr = Nn - carn
    roses = Rr / 2 + 3
    chry = Rr - roses
    if chry == 5 and roses.denominator == 1:
        sol.append((Nn, int(carn)))
assert len(sol) == 1
check(V, 9, 4, [(25, 10), (27, 11), (35, 16), (28, 12)], sol[0], f"решение {sol}")
div4 = [o[0] % 4 == 0 for o in [(25, 10), (27, 11), (35, 16), (28, 12)]]
RESULTS.append((V, 9, "-", "-", "ЗАМЕЧАНИЕ", f"N делится на 4 только в варианте 4 (отсев по делимости): {div4}"))

# 10. Объём шара ×64 → радиус ×64^(1/3)
check(V, 10, 1, [4, 64, 6, 2], round(64 ** (1 / 3)))

# =============================== ВАРИАНТ 16498 ===============================
V = 16498
# 1. (x+1/x)^2 = 5 → x^4 + 1/x^4  (проверка на реальном x)
t = 5 ** 0.5
xx = (t + (t * t - 4) ** 0.5) / 2          # корень x + 1/x = √5 (существует, т.к. 5 ≥ 4)
val = xx ** 4 + 1 / xx ** 4
check(V, 1, 3, [0, 2, 7, 5], round(val), f"x≈{xx:.4f}; значение {val:.6f}")

# 2. Температура (таблица)
tm = [6, 9, 12, 15]
tp = [-12, -8, -5, -7]
pairs = [(tm[j] - tm[i]) for i in range(4) for j in range(i + 1, 4) if tp[j] - tp[i] == 7]
check(V, 2, 2, [3, 6, 4, 7], pairs[0], f"подходящих пар: {pairs}")

# 3. Среднее по таблице оценок
marks = {5: 2, 4: 4, 3: 10, 2: 4, 1: 0}
mean = F(sum(m * c for m, c in marks.items()), sum(marks.values()))
check(V, 3, 1, [F("3.2"), F("3.25"), F(3), F("3.4")], mean, f"{mean}")

# 4. Вероятность (то же задание №1655)
check(V, 4, 1, [F(1, 5), F(7, 10), F(4, 5), F(2, 5)], F("информация".count("и"), 10))

# 5. Периметр 85, a:b=1:2, b:c=3:4
#    a:b:c = 3:6:8 → 17 частей
part = F(85, 3 + 6 + 8)
a_, b_, c_ = 3 * part, 6 * part, 8 * part
assert a_ / b_ == F(1, 2) and b_ / c_ == F(3, 4) and a_ + b_ > c_
check(V, 5, 1, [25, 15, 27, 10], c_ - a_, f"стороны {a_}, {b_}, {c_}; 15 — наименьшая сторона (ловушка)")

# 6. Давление, вторник (ПО РИСУНКУ): кривая стартует на левой границе осей с 751
tue_min = 751
check(V, 6, 4, [754, 752, 756, 751], tue_min, "минимум во вторник лежит на самой границе оси (начало кривой)")

# 7. «логарифм»: 3 согласные и 1 гласная
word = "логарифм"
vow = [c for c in word if c in "аеёиоуыэюя"]
con = [c for c in word if c not in "аеёиоуыэюя"]
check(V, 7, 4, [13, 64, 448, 30], comb(len(con), 3) * comb(len(vow), 1),
      f"согл. {len(con)}, гласн. {len(vow)}")

# 8. Мать 43, дочь 15: (43+x)/(15+x) = 5/3
xs = [x for x in range(0, 200) if F(43 + x, 15 + x) == F(5, 3)]
check(V, 8, 1, [27, 29, 25, 24], xs[0])

# 9. Весы: 4я + 4с = 48; я = с + 8
sols = [(a, s_) for s_ in range(0, 49) for a in range(0, 49)
        if 4 * a + 4 * s_ == 48 and a == s_ + 8]
check(V, 9, 3, [4, 3, 5, 6], F(sols[0][0], sols[0][1]), f"яблоко={sols[0][0]} конфет, слива={sols[0][1]}")

# 10. Икосаэдр: 12 вершин, 20 граней → рёбер = 12+20−2 = 30
check(V, 10, 1, [30, 20, 24, 12], 12 + 20 - 2, "формула Эйлера; в PDF рисунок — икосаэдр")

# =============================== ВАРИАНТ 16979 ===============================
V = 16979
# 1. a1:a2=a3:a4; a2=3/4 a1; a3=2/3 a1; a1+a2+a3=58
cand = [a1 for a1 in range(1, 500) if a1 + F(3, 4) * a1 + F(2, 3) * a1 == 58]
a1 = cand[0]
a2, a3 = F(3, 4) * a1, F(2, 3) * a1
a4 = a2 * a3 / a1
check(V, 1, 4, [13, 14, 15, 12], a4, f"a1={a1}, a2={a2}, a3={a3}")

# 2. Крахмал 0,9 кг из 5 кг
check(V, 2, 1, [F(18), F(14), F(21), F(15)], F("0.9") / 5 * 100)

# 3. Медиана ряда
ser = sorted([15, 21, 16, 18, 12, 25, 11])
check(V, 3, 2, [18, 16, 25, 15], ser[len(ser) // 2])

# 4. Вероятность (№1655)
check(V, 4, 1, [F(1, 5), F(7, 10), F(4, 5), F(2, 5)], F("информация".count("и"), 10))

# 5. Масштаб: 14 см при 1:500000 → при 1:750000
check(V, 5, 4, [F(9, 5), F(14, 5), F(7, 3), F(28, 3)], F(14 * 500_000, 750_000),
      "= 9 1/3 см. Реализм: 14 см×500000 = 70 км, реальное расстояние Семей—Усть-Каменогорск заметно больше")

# 6. 30% от 360°
check(V, 6, 2, [110, 108, 100, 124], F(30, 100) * 360)

# 7. АС… из букв А,И,О,Р,С,Т
letters = "АИОРСТ"
cnt = sum(1 for p_ in permutations(letters) if "".join(p_).startswith("АС"))
check(V, 7, 3, [4, 6, 24, 20], cnt)

# 8. 12(256)4 → (12+4)^2 ; 14(?)5
assert (12 + 4) ** 2 == 256
check(V, 8, 4, [225, 441, 324, 361], (14 + 5) ** 2)

# 9. Арифметическая прогрессия: a1=20, 8 дней, сумма 440
d_ = [d for d in range(0, 100) if 8 * 20 + 28 * d == 440]
check(V, 9, 2, [8, 10, 16, 15], d_[0], "при чтении «ещё 8 дней после первого» получилось бы d≈7,2 (нет среди ответов) → в условии лучше явно написать «включая первый день»")

# 10. Куб: 6a^2=384
a_cube = next(a for a in range(1, 100) if 6 * a * a == 384)
check(V, 10, 2, [625, 512, 127, 64], a_cube ** 3)


# =================================== ВЫВОД ===================================
def main():
    print(f"{'вар.':<6}{'№':<4}{'ключ PDF':<10}{'вычислено':<12}{'статус':<22}комментарий")
    print("-" * 110)
    for r in RESULTS:
        print(f"{r[0]:<6}{r[1]:<4}{str(r[2]):<10}{str(r[3]):<12}{r[4]:<22}{r[5]}")
    real = [r for r in RESULTS if r[4] != "ЗАМЕЧАНИЕ"]
    ok = sum(1 for r in real if r[4] == "OK")
    print(f"\nИтого: {len(real)} заданий, ключ подтверждён: {ok}, расхождений: {len(real) - ok}")

    keys = {18461: [3, 1, 1, 1, 1, 1, 4, 1, 4, 1],
            16498: [3, 2, 1, 1, 1, 4, 4, 1, 3, 1],
            16979: [4, 1, 2, 1, 4, 2, 3, 4, 2, 2]}
    tot = Counter()
    for v, ks in keys.items():
        c = Counter(ks)
        tot.update(c)
        print(f"Ключ {v}: позиции ответов 1/2/3/4 = {c[1]}/{c[2]}/{c[3]}/{c[4]}")
    print(f"Все 30: 1/2/3/4 = {tot[1]}/{tot[2]}/{tot[3]}/{tot[4]}  (доля «1» = {tot[1]/30:.0%}, ожидалось ≈25%)")


if __name__ == "__main__":
    main()
