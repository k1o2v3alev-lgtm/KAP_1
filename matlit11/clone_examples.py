# ------------------------------- форматирование -------------------------------
def fmt(v, frac=False):
    if isinstance(v, tuple):
        return ", ".join(str(fmt(x)) for x in v)
    if isinstance(v, F):
        if v.denominator == 1:
            return str(v.numerator)
        if frac:
            return f"{v.numerator}/{v.denominator}"
        d = v.denominator
        dd = d
        for p in (2, 5):
            while dd % p == 0:
                dd //= p
        if dd == 1:                                   # конечная десятичная дробь
            s = f"{float(v):.10f}".rstrip("0").rstrip(".")
            return s.replace(".", ",")
        whole, rem = divmod(v.numerator, v.denominator)
        return f"{whole} {rem}/{d}" if whole else f"{v.numerator}/{d}"
    return str(v).replace(".", ",") if isinstance(v, float) else str(v)


class Task:
    def __init__(self, slot, family, mode, diff, level, text, ans, wrongs, unit="", frac=False):
        self.slot, self.family, self.mode, self.diff, self.level = slot, family, mode, diff, level
        self.text, self.ans, self.wrongs, self.unit, self.frac = text, ans, wrongs, unit, frac  # wrongs: [(значение, «почему»)]

    def validate(self):
        vals = [self.ans] + [w[0] for w in self.wrongs]
        assert len(self.wrongs) == 3, f"слот {self.slot}: нужно ровно 3 дистрактора"
        assert len({fmt(v) for v in vals}) == 4, f"слот {self.slot}: варианты совпадают {vals}"


def tasks_demo():
    T = []

    # ---- Слот 1 (обратная): пропорция, найти сумму по a4 --------------------------
    # a1:a2 = a3:a4, a2 = 1/2 a1, a3 = 2/3 a1, a4 = 8 → сумма первых трёх
    a4 = 8
    a1 = next(x for x in range(1, 1000) if F(1, 2) * x * F(2, 3) * x / x == a4)   # a4 = a2*a3/a1
    a2, a3 = F(1, 2) * a1, F(2, 3) * a1
    assert a2 * a3 / a1 == a4 and a1 * a4 == a2 * a3
    s = a1 + a2 + a3
    T.append(Task(1, "1C пропорция", "I", 3, "Б",
                  "Дана пропорция a₁ : a₂ = a₃ : a₄. Второй член составляет 1/2, а третий 2/3 первого члена. "
                  "Четвёртый член равен 8. Найдите сумму первых трёх членов пропорции.",
                  s, [(F(a1), "найдено только a₁"), (a1 + a2, "сложены только a₁ и a₂"), (a2 + a3, "сложены a₂ и a₃")]))

    # ---- Слот 2 (прямая): таблица двух сортов, разность процентного содержания ------------------
    M1, m1, M2, m2 = F(5), F("0.9"), F(8), F("1.28")
    p1, p2 = m1 / M1 * 100, m2 / M2 * 100
    T.append(Task(2, "2B проценты/таблица", "D", 2, "Б",
                  "В таблице даны массы картофеля и содержащегося в нём крахмала для двух сортов: "
                  "сорт 1 — картофель 5 кг, крахмал 0,9 кг; сорт 2 — картофель 8 кг, крахмал 1,28 кг. "
                  "На сколько процентных пунктов содержание крахмала в сорте 1 больше, чем в сорте 2?",
                  p1 - p2, [(abs(m1 - m2), "взята разность масс крахмала (0,38)"),
                            (M2 - M1, "взята разность масс картофеля"), (p1 / p2, "найдено отношение процентов, а не разность")],
                  ""))

    # ---- Слот 3 (прямая): медиана выборки с частотами, порядок значений ЗАДАН ----------
    freq = [8, 5, 6, 3, 3]
    ser = [i for i, f in enumerate(freq, 1) for _ in range(f)]
    n = len(ser)
    assert n % 2 == 1
    med = ser[n // 2]
    mode = freq.index(max(freq)) + 1
    assert med != mode and med != 3
